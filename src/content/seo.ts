/** JSON-LD type of the page itself. `Service` pages get a WebPage node plus Service nodes. */
export type PageSchema = 'WebPage' | 'CollectionPage' | 'AboutPage' | 'ContactPage' | 'Service'

export type Crumb = { name: string; path: string }

export type SeoPage = {
  id: PageId
  /** HTML entry, relative to the project root. */
  file: string
  /** Clean URL path, no trailing slash ('/' for home). */
  path: string
  title: string
  description: string
  ogTitle?: string
  ogDescription?: string
  /** Text on the 1200×630 social card (public/og/<id>.png): the page's hero (content/heroes.ts), also its alt text. */
  card: { kicker: string; title: string }
  /** Home → … → this page. Empty for home and noindex pages. */
  breadcrumb: Crumb[]
  schema: PageSchema
  indexable: boolean
  /** Slug in `systemPages`, for Service data. */
  system?: string
  /** Name of the Service on a system page. */
  serviceName?: string
  /** llms.txt section and link label. */
  llms?: { section: 'Websites' | 'Systems' | 'AI' | 'Company' | 'Contact' | 'Legal'; label: string }
}

const HOME: Crumb = { name: 'Home', path: '/' }
const SERVICES: Crumb = { name: 'Our services', path: '/our-services' }

function systemPage(
  slug: string,
  p: Pick<SeoPage, 'id' | 'title' | 'description' | 'serviceName'>,
): SeoPage {
  const sys = systemPages.find((s) => s.slug === slug)
  if (!sys) throw new Error(`seo: no system page "${slug}"`)
  const path = `/systems/${slug}`
  return {
    id: p.id,
    file: `systems/${slug}.html`,
    path,
    title: p.title,
    description: p.description,
    card: heroCard(sys.slug),
    breadcrumb: [HOME, SERVICES, { name: sys.title, path }],
    schema: 'Service',
    indexable: true,
    system: slug,
    serviceName: p.serviceName,
    llms: { section: 'Systems', label: sys.title },
  }
}

